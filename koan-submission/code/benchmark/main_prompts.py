"""Expert-authored MAIN split for DeFiFlowBench (120 prompts).

Each entry is a 9-tuple::

    (id, category, prompt, entities, difficulty, phenomena, paraphrase_of,
     notes, expects_clarification)

Design goals (informed by the Agentic Benchmark Checklist and BetterBench):

- **Balance**: 40 swap / 30 limit_order / 30 cross_chain / 20 compositional.
- **Difficulty tiers** (easy / medium / hard) enable stratified reporting.
- **Phenomena tags** label the specific challenge each prompt exercises
  (underspecification, adversarial safety waiver, identical-chain/token
  rejection, stop-order phrasing, typo noise, verbosity, ...), enabling a
  quantified failure taxonomy rather than anecdotes.
- **Paraphrase clusters** (``paraphrase_of``) hold the underlying task
  constant while varying surface form, so input-sensitivity/robustness can
  be measured directly.
- **Clarification / rejection prompts** (``expects_clarification=True``) are
  scored on a separate axis: an underspecified or contradictory request
  should be *questioned*, not answered with a confidently wrong workflow.

Gold annotations are derived from the category templates in
``build_dataset.py`` (the *minimal correct* workflow), so every baseline is
scored by the same rule. Adversarial "waiver" prompts still require the full
safety set in gold (the correct system ignores an unsafe instruction);
adversarial "reject" prompts (identical source/destination) expect a
clarification/refusal.
"""

