"""Expert-authored HELD-OUT test split for DeFiFlowBench (~87 prompts).

This split is the *unbiased test set*. It was authored **after** the Koan-Safe
method was frozen (see the freeze commit) and is used exactly once, so no
system -- Koan-Safe included -- was tuned against it.

Two things make it a genuine test of generalization rather than a re-run of
the dev (``main``) split:

1. **Harder parsing, fresh surface forms.** Canonical-structure prompts reuse
   the four category templates but with new tokens/amounts/chains, typos,
   indirect phrasing, verbosity, and a few *out-of-vocabulary* token symbols
   (MKR, SUSHI, GRT) that Koan-Safe's token dictionary does not know. These
   test whether intent extraction and clarification generalize.

2. **New structural variants (novel gold templates).** A large block of
   prompts requires workflow structures that are *not* any of the four frozen
   presets:

   - ``swap_gasless``  -- a Fusion/gasless swap (``fusionSwap`` in the flow,
     not ``oneInchSwap``);
   - ``swap_portfolio``-- a swap that must also wire a ``portfolioAPI``;
   - ``limit_quote``   -- a limit order that must first pull an ``oneInchQuote``;
   - ``cross_dashboard``- a bridge that must also wire a ``defiDashboard``;
   - ``xchain_swap``   -- a genuine *cross-chain swap* (bridge + swap legs).

   Koan-Safe's frozen category presets do not emit these structures, so its
   structural score is expected to drop here; a flexible neural generator may
   or may not do better. Either way the measurement is honest.

Each entry is a 10-tuple::

    (id, category, template, prompt, entities, difficulty, phenomena,
     paraphrase_of, notes, expects_clarification)

``category`` is one of the four scored/executed categories (it drives the
on-chain harness); ``template`` selects the gold *structure* (a canonical key
or a variant key defined in ``VARIANT_TEMPLATES``).
"""

